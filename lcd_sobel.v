// ============================================================================
// lcd_sobel.v — 流式 Sobel 边缘检测模块
//
// 功能：对输入的 RGB888 像素流进行 Sobel 边缘检测
//       使用 2 行行缓冲 + 3x3 窗口实现流式处理
//
// 参考算法：main.cpp 中的 Sobel()
//   Gx = {{-1,0,1}, {-2,0,2}, {-1,0,1}}   — 检测垂直边缘
//   Gy = {{-1,-2,-1}, {0,0,0}, {1,2,1}}   — 检测水平边缘
//   边缘幅值 = |Gx| + |Gy|
// ============================================================================

module lcd_sobel(
    input               lcd_clk,            // LCD 像素时钟 (~33.3 MHz)
    input               sys_rst_n,          // 复位信号（低有效）
    input      [10:0]   pixel_xpos,         // 当前像素 X 坐标 (0~799)
    input      [10:0]   pixel_ypos,         // 当前像素 Y 坐标 (0~479)
    input      [23:0]   pixel_data_in,      // 原始 RGB888 像素输入
    output     [23:0]   pixel_data_out      // 边缘检测 RGB888 像素输出
);

//=============================================================================
// 参数
//=============================================================================
localparam H_DISP = 11'd800;   // 显示宽度

//=============================================================================
// Stage 1: 灰度转换
// gray = (R + G + B) / 4  (使用右移2位代替除以3，硬件更高效)
// 对于边缘检测，灰度值的绝对大小不重要，差异才是关键
//=============================================================================
wire [9:0] sum_rgb;
wire [7:0] gray;

assign sum_rgb = pixel_data_in[23:16] + pixel_data_in[15:8] + pixel_data_in[7:0];
assign gray   = sum_rgb[9:2];  // 右移2位 ≈ 除以4

//=============================================================================
// Stage 2: 行缓冲 (2条线缓冲，每条800深度 × 8bit)
//          使用推断的块 RAM，读旧写新模式
//=============================================================================
reg [7:0] line_buf0 [0:H_DISP-1];  // 存储 row-2 行的灰度值
reg [7:0] line_buf1 [0:H_DISP-1];  // 存储 row-1 行的灰度值

//=============================================================================
// Stage 3: 3x3 卷积窗口寄存器
//   窗口排列：
//     a3 a2 a1   ← (x-2, y-2)  (x-1, y-2)  (x, y-2)
//     b3 b2 b1   ← (x-2, y-1)  (x-1, y-1)  (x, y-1)
//     c3 c2 c1   ← (x-2, y)    (x-1, y)    (x, y)
//   中心像素 = b2 = (x-1, y-1)
//=============================================================================
reg [7:0] a1, a2, a3;  // row-2
reg [7:0] b1, b2, b3;  // row-1
reg [7:0] c1, c2, c3;  // current row

always @(posedge lcd_clk or negedge sys_rst_n) begin
    if (!sys_rst_n) begin
        a1 <= 8'd0; a2 <= 8'd0; a3 <= 8'd0;
        b1 <= 8'd0; b2 <= 8'd0; b3 <= 8'd0;
        c1 <= 8'd0; c2 <= 8'd0; c3 <= 8'd0;
    end else begin
        // --- 当前行流水线 (c) ---
        c3 <= c2;
        c2 <= c1;
        c1 <= gray;  // 当前像素灰度值

        // --- 上一行流水线 (b)：从 line_buf1 读取 ---
        b1 <= line_buf1[pixel_xpos];  // 读取 (x, y-1) 旧数据
        b3 <= b2;
        b2 <= b1;

        // --- 上两行流水线 (a)：从 line_buf0 读取 ---
        a1 <= line_buf0[pixel_xpos];  // 读取 (x, y-2) 旧数据
        a3 <= a2;
        a2 <= a1;

        // --- 行缓冲写入 (非阻塞赋值，RHS 同时求值) ---
        line_buf1[pixel_xpos] <= gray;                 // 当前行写入 buf1 (供下一帧行使用)
        line_buf0[pixel_xpos] <= line_buf1[pixel_xpos]; // buf1 旧值移入 buf0
    end
end

//=============================================================================
// Stage 4: Sobel 卷积计算
//   Gx = (a1 + 2*b1 + c1) - (a3 + 2*b3 + c3)
//   Gy = (c3 + 2*c2 + c1) - (a3 + 2*a2 + a1)
//   乘以2使用左移1位实现: {b1,1'b0} = b1 * 2
//=============================================================================
wire [10:0] gx, gy;

assign gx = (a1 + {b1, 1'b0} + c1) - (a3 + {b3, 1'b0} + c3);
assign gy = (c3 + {c2, 1'b0} + c1) - (a3 + {a2, 1'b0} + a1);

//=============================================================================
// Stage 5: 边缘幅值计算
//   mag = |Gx| + |Gy|
//   (近似 sqrt(Gx²+Gy²)，硬件实现简单)
//=============================================================================
wire [10:0] gx_abs, gy_abs;
wire [11:0] mag;

assign gx_abs = gx[10] ? (~gx + 1'b1) : gx;  // 绝对值
assign gy_abs = gy[10] ? (~gy + 1'b1) : gy;
assign mag   = gx_abs + gy_abs;

// 钳位到 [0, 255]
wire [7:0] edge_val;
assign edge_val = (mag > 8'd255) ? 8'd255 : mag[7:0];

//=============================================================================
// Stage 6: 输出寄存器 — 将边缘幅值输出为灰度 RGB
//=============================================================================
reg [7:0] edge_r, edge_g, edge_b;

always @(posedge lcd_clk or negedge sys_rst_n) begin
    if (!sys_rst_n) begin
        edge_r <= 8'd0;
        edge_g <= 8'd0;
        edge_b <= 8'd0;
    end else begin
        edge_r <= edge_val;
        edge_g <= edge_val;
        edge_b <= edge_val;
    end
end

assign pixel_data_out = {edge_r, edge_g, edge_b};

endmodule
